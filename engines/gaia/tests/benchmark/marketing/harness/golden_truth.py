"""Golden-truth producer: run the expected_sql files against MySQL (DESIGN.md §5.2).

Read path: connect to the source MySQL (fixture-seeded), run each L*.sql with
bound parameters, return rows. This is the "physical direct-connect" oracle
(DESIGN.md §2.2: read path has NO direct-connect restriction; expected is
derived by物理 SQL, not hand-written).

The L*.sql files use ``:param`` placeholders. We convert them to MySQL
``%s`` positional placeholders and bind params in the order they appear
(parameter binding, no string concat — DESIGN.md §6.3 anti-injection).
"""

from __future__ import annotations

import logging
import re
from pathlib import Path
from typing import Any

import aiomysql

log = logging.getLogger("golden_truth")

EXPECTED_SQL_DIR = Path(__file__).resolve().parents[1] / "data" / "expected_sql"

# Default MySQL connection (marketing-mysql container / localhost mapping).
DEFAULT_MYSQL = {
    "host": "localhost",
    "port": 3306,
    "user": "root",
    "password": "marketing123",
    "db": "marketing_benchmark",
    "charset": "utf8mb4",
}

_PARAM_RE = re.compile(r":([a-zA-Z_][a-zA-Z0-9_]*)")


def _convert_sql(sql: str, params: dict[str, Any]) -> tuple[str, list[Any]]:
    """Convert ``:name`` placeholders to positional ``%s`` for aiomysql.

    Preserves order of first appearance. Raises if a param is referenced but
    not provided (fail-loud — better than a silent wrong-row result).
    """
    seen: list[str] = []
    seen_set: set[str] = set()
    for m in _PARAM_RE.finditer(sql):
        name = m.group(1)
        if name not in seen_set:
            seen_set.add(name)
            seen.append(name)
    missing = [n for n in seen if n not in params]
    if missing:
        raise ValueError(f"missing params for SQL: {missing}")
    positional = [_PARAM_RE.sub("%s", sql), [params[n] for n in seen]]
    # aiomysql (PyMySQL) treats % as a format specifier in parameterized
    # queries. Escape literal % (e.g. inside LIKE CONCAT(:date, '%')) as %%
    # so PyMySQL emits a single %. Without this, "not enough arguments for
    # format string" is raised on any SQL containing a literal '%'.
    conv_sql = positional[0].replace("%", "%%").replace("%s", "%s")
    # The above double-replaces %s placeholders too; restore them. Simpler:
    # escape % only where it's NOT part of %s.
    conv_sql = positional[0]
    # Replace literal '%' not followed by 's' (i.e. not a %s placeholder) with '%%'.
    conv_sql = re.sub(r"%(?!s)", "%%", conv_sql)
    return conv_sql, [params[n] for n in seen]


def load_sql(case_id: str) -> str:
    """Read the expected_sql file for a case id (e.g. 'L1', 'L3-bis')."""
    p = EXPECTED_SQL_DIR / f"{case_id}.sql"
    if not p.exists():
        raise FileNotFoundError(f"expected SQL not found: {p}")
    text = p.read_text(encoding="utf-8")
    # Strip `-- ` line comments (avoid breaking on semicolons inside comments).
    lines = [ln for ln in text.splitlines() if not ln.strip().startswith("--")]
    cleaned = "\n".join(lines).strip()
    # Expected SQL is a single statement per file.
    return cleaned.rstrip(";").strip()


async def run_expected(
    case_id: str,
    params: dict[str, Any],
    mysql: dict[str, Any] | None = None,
) -> list[dict[str, Any]]:
    """Run a case's expected SQL against MySQL, return rows as dicts.

    DESIGN.md §5.2: this is the黄金真值 derivation, read-only on MySQL.
    For Tier2 cases whose backing table doesn't exist yet (e.g. L7-bis
    competitive_analysis is an AI product generated by Action W7, not yet
    run), returns an empty list instead of raising — the case then XFAILs
    cleanly rather than ERRORing on a missing-table ProgrammingError.
    """
    sql = load_sql(case_id)
    conv_sql, positional = _convert_sql(sql, params)
    cfg = {**DEFAULT_MYSQL, **(mysql or {})}
    conn = await aiomysql.connect(
        host=cfg["host"],
        port=cfg["port"],
        user=cfg["user"],
        password=cfg["password"],
        db=cfg["db"],
        autocommit=True,
        charset=cfg.get("charset", "utf8mb4"),
    )
    try:
        async with conn.cursor(aiomysql.DictCursor) as cur:
            await cur.execute(conv_sql, positional)
            rows = await cur.fetchall()
            return [dict(r) for r in rows]
    except aiomysql.MySQLError as e:
        # 1146 = table doesn't exist. AI-product tables (competitive_analysis,
        # etc.) don't exist until W7/W8 generate them. Return empty so Tier2
        # cases XFAIL rather than ERROR.
        if getattr(e, "args", [None])[0] == 1146:
            log.warning("expected SQL %s: table missing (%s) → returning []", case_id, str(e)[:80])
            return []
        raise
    finally:
        conn.close()


async def probe_params(case_id: str, mysql: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """Run with empty params — only valid for param-free cases. Mostly used
    for smoke-testing the SQL parses. Returns rows."""
    return await run_expected(case_id, {}, mysql)
