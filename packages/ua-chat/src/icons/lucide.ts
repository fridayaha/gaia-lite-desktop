const IMAGE_EXTS = [".png", ".jpg", ".jpeg", ".gif", ".svg", ".webp", ".ico", ".bmp"]
const MD_EXTS = [".md", ".markdown", ".mdown"]
const CODE_ZAP_EXTS = [".js", ".ts", ".jsx", ".tsx"]
const SETTINGS_EXTS = [".json", ".yaml", ".yml", ".toml", ".ini", ".cfg"]
const TERM_EXTS = [".sh", ".bash", ".zsh"]

/** 文件名 → Lucide 图标名（移植自 hermes-webui fileIcon） */
export function fileIconName(name: string, isDir: boolean): string {
  if (isDir) return "folder"
  const e = name.toLowerCase().match(/\.[^.]+$/)?.[0] || ""
  if (IMAGE_EXTS.includes(e)) return "image"
  if (MD_EXTS.includes(e)) return "file-text"
  if (e === ".py") return "file-code"
  if (CODE_ZAP_EXTS.includes(e)) return "zap"
  if (SETTINGS_EXTS.includes(e)) return "settings"
  if (TERM_EXTS.includes(e)) return "terminal"
  return "file-text"
}
